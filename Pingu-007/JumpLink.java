
public class JumpLink {

    public int origemCol, origemRow;
    public int destinoCol, destinoRow;
    public int distanciaTiles;

    public JumpLink(int origemCol, int origemRow, int destinoCol, int destinoRow, int distanciaTiles) {
        this.origemCol = origemCol;
        this.origemRow = origemRow;
        this.destinoCol = destinoCol;
        this.destinoRow = destinoRow;
        this.distanciaTiles = distanciaTiles;
    }
}
